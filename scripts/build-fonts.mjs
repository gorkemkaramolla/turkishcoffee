/*
 * Builds the typeface the library ships: Inter, subset to the characters a
 * Turkish and English interface uses, with both variable axes (wght 100–900,
 * opsz 14–32) and every OpenType feature kept. Also writes a fallback face
 * whose metrics match Inter, so text keeps its size and line breaks while the
 * font loads.
 *
 *   node scripts/build-fonts.mjs
 *
 * Writes src/styles/fonts/*.woff2, src/styles/fonts/OFL.txt and
 * src/styles/fonts.css. The output is committed; rerun after changing the
 * character set or upgrading inter-ui.
 */
import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import subsetFont from 'subset-font'
import { fromBuffer } from '@capsizecss/unpack'
import { createFontStack } from '@capsizecss/core'
import arial from '@capsizecss/metrics/arial'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
const interDir = dirname(require.resolve('inter-ui/package.json'))
const outDir = join(root, 'src/styles/fonts')

/*
 * [first, last] code point ranges. Latin-1 holds Ç Ö Ü and the circumflex
 * vowels; Ğ İ ı Ş are listed on their own. The combining dot (U+0307) shows up
 * when İ is lowercased outside a Turkish locale, so it is kept rather than
 * falling back to another font mid-word.
 */
const ranges = [
  [0x0020, 0x007e], // Basic Latin
  [0x00a0, 0x00ff], // Latin-1: Ç ç Ö ö Ü ü Â â Î î Û û, ©, °, ×
  [0x011e, 0x011f], // Ğ ğ
  [0x0130, 0x0131], // İ ı
  [0x015e, 0x015f], // Ş ş
  [0x0152, 0x0153], // Œ œ
  [0x02c6, 0x02c6],
  [0x02da, 0x02da],
  [0x02dc, 0x02dc],
  [0x0300, 0x0308], // combining accents, incl. the dot above
  [0x2000, 0x206f], // General Punctuation: – — ‘ ’ “ ” … • ‰ ′
  [0x20ac, 0x20ac], // €
  [0x20ba, 0x20ba], // ₺
  [0x2122, 0x2122], // ™
  [0x2190, 0x2193], // ← ↑ → ↓
  [0x2212, 0x2212], // − (minus)
  [0x2215, 0x2215],
  [0xfeff, 0xfeff],
  [0xfffd, 0xfffd],
]

const text = ranges.flatMap(([a, b]) => Array.from({ length: b - a + 1 }, (_, i) => String.fromCodePoint(a + i))).join('')
const unicodeRange = ranges
  .map(([a, b]) => (a === b ? `U+${hex(a)}` : `U+${hex(a)}-${hex(b)}`))
  .join(', ')

function hex(n) {
  return n.toString(16).toUpperCase().padStart(4, '0')
}

/*
 * The OpenType features an interface uses: shaping and kerning, contextual and
 * case-sensitive forms, the Turkish locl, tabular and proportional figures,
 * slashed zero and fractions. Inter's character variants and stylistic sets
 * (cv01–cv13, ss01–ss08) are dropped: they double the file size and nothing in
 * the library turns them on.
 */
const keepFeatures = ['ccmp', 'locl', 'calt', 'case', 'kern', 'mark', 'mkmk', 'rvrn', 'rclt', 'tnum', 'pnum', 'zero', 'frac', 'numr', 'dnom']

await mkdir(outDir, { recursive: true })

const faces = [
  { file: 'inter-roman.woff2', source: 'variable/InterVariable.woff2', style: 'normal' },
  { file: 'inter-italic.woff2', source: 'variable/InterVariable-Italic.woff2', style: 'italic' },
]

for (const face of faces) {
  const source = await readFile(join(interDir, face.source))
  const subset = await subsetFont(source, text, { targetFormat: 'woff2', keepFeatures })
  await writeFile(join(outDir, face.file), subset)
  face.bytes = subset.length
}
await copyFile(join(interDir, 'LICENSE.txt'), join(outDir, 'OFL.txt'))

/*
 * The fallback face: Arial (Windows, macOS) or its metric twin Liberation Sans
 * (Linux), scaled and given Inter's ascent, descent and line gap.
 */
const inter = await fromBuffer(await readFile(join(interDir, faces[0].source)))
const { fontFaces } = createFontStack([{ ...inter, familyName: 'Inter' }, arial])
const fallback = fontFaces
  .replace(/font-family: "[^"]+";/, 'font-family: "Inter Fallback";')
  .replace(/src: local\([^;]+\);/, 'src: local("Arial"), local("ArialMT"), local("Liberation Sans");')

const css = `/*
 * Generated by scripts/build-fonts.mjs. Do not edit; rerun the script.
 *
 * Inter ${require('inter-ui/package.json').version} (SIL Open Font License 1.1, see fonts/OFL.txt),
 * subset to Latin, Latin-1 and Turkish, with the wght (100–900) and opsz
 * (14–32) axes. A face downloads only when text on the page uses it, so the
 * italic costs nothing until something is set in italic.
 */
${faces
  .map(
    (face) => `@font-face {
    font-family: "Inter";
    font-style: ${face.style};
    font-weight: 100 900;
    font-display: swap;
    src: url("./fonts/${face.file}") format("woff2");
    unicode-range: ${unicodeRange};
}`,
  )
  .join('\n\n')}

/* Arial resized to Inter's metrics: holds the layout until Inter arrives. */
${fallback.trim()}
`

await writeFile(join(root, 'src/styles/fonts.css'), css)

for (const face of faces) console.log(`${face.file}: ${(face.bytes / 1024).toFixed(1)} KB`)
console.log(`${[...text].length} characters`)
